import type { PrdModel } from './sections'
import { parseDataModels, extractRelationships, type ParsedEntity } from './diagramParser'

export type SqlDialect = 'postgresql' | 'mysql' | 'sqlite'

/**
 * Maps field type to specific SQL column definitions per dialect.
 */
function mapFieldToSqlType(
  field: { name: string; type: string; isPk: boolean },
  dialect: SqlDialect,
): string {
  const t = field.type.toUpperCase()

  if (field.isPk) {
    if (dialect === 'postgresql') return 'BIGSERIAL PRIMARY KEY'
    if (dialect === 'mysql') return 'BIGINT AUTO_INCREMENT PRIMARY KEY'
    if (dialect === 'sqlite') return 'INTEGER PRIMARY KEY AUTOINCREMENT'
  }

  if (t.includes('INT') || t.includes('SERIAL')) {
    if (t.includes('BIG')) return dialect === 'sqlite' ? 'INTEGER' : 'BIGINT'
    if (t.includes('SMALL')) return dialect === 'sqlite' ? 'INTEGER' : 'SMALLINT'
    return dialect === 'sqlite' ? 'INTEGER' : 'INTEGER'
  }

  if (t.includes('BOOL')) {
    if (dialect === 'sqlite') return 'INTEGER DEFAULT 0'
    if (dialect === 'mysql') return 'TINYINT(1) DEFAULT 0'
    return 'BOOLEAN DEFAULT FALSE'
  }

  if (t.includes('FLOAT') || t.includes('DOUBLE') || t.includes('DECIMAL') || t.includes('NUMERIC')) {
    if (dialect === 'sqlite') return 'REAL'
    if (dialect === 'postgresql') return 'DOUBLE PRECISION'
    return 'DOUBLE'
  }

  if (t.includes('TIMESTAMP') || t.includes('DATE') || t.includes('TIME')) {
    if (dialect === 'sqlite') return 'TEXT DEFAULT (datetime(\'now\'))'
    if (dialect === 'mysql') return 'DATETIME DEFAULT CURRENT_TIMESTAMP'
    return 'TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP'
  }

  if (t.includes('JSON')) {
    if (dialect === 'sqlite') return 'TEXT'
    if (dialect === 'mysql') return 'JSON'
    return 'JSONB DEFAULT \'{}\'::jsonb'
  }

  if (t.includes('TEXT')) {
    return 'TEXT'
  }

  if (t.includes('UUID')) {
    if (dialect === 'postgresql') return 'UUID DEFAULT gen_random_uuid()'
    return 'VARCHAR(36)'
  }

  return 'VARCHAR(255)'
}

/**
 * Generates production-ready SQL DDL statements for a list of parsed entities.
 */
export function generateSqlDdl(entities: ParsedEntity[], dialect: SqlDialect = 'postgresql'): string {
  if (entities.length === 0) {
    return `-- No structured data models detected in Section 08.\n-- Example: - **users**: id (PK), email (VARCHAR), created_at (TIMESTAMP)\n`
  }

  const relationships = extractRelationships(entities)
  const lines: string[] = []

  lines.push(`-- =============================================================================`)
  lines.push(`-- Database DDL Schema Migration (${dialect.toUpperCase()})`)
  lines.push(`-- Auto-generated by BlueprintDev Specification Engine`)
  lines.push(`-- =============================================================================\n`)

  if (dialect === 'postgresql') {
    lines.push(`-- Ensure UUID generation extension is active`)
    lines.push(`CREATE EXTENSION IF NOT EXISTS "uuid-ossp";\n`)
  }

  // Create tables
  for (const entity of entities) {
    lines.push(`CREATE TABLE IF NOT EXISTS ${entity.name} (`)
    const colDefs: string[] = []

    for (const field of entity.fields) {
      const sqlType = mapFieldToSqlType(field, dialect)
      let colDef = `    ${field.name} ${sqlType}`
      if (field.isPk) {
        // already has PRIMARY KEY
      } else if (!sqlType.includes('DEFAULT') && !sqlType.includes('NULL')) {
        colDef += ' NOT NULL'
      }
      colDefs.push(colDef)
    }

    // Add Foreign Key Constraints
    if (dialect !== 'sqlite') {
      const entityFks = relationships.filter((r) => r.toTable === entity.name)
      for (const fk of entityFks) {
        colDefs.push(
          `    CONSTRAINT fk_${entity.name}_${fk.fromField} FOREIGN KEY (${fk.fromField}) REFERENCES ${fk.fromTable}(id) ON DELETE CASCADE`,
        )
      }
    }

    lines.push(colDefs.join(',\n'))
    lines.push(`);\n`)
  }

  // Create Index on Foreign Keys and High-Cardinality Columns
  lines.push(`-- =============================================================================`)
  lines.push(`-- Relational Foreign Key Performance Indexes`)
  lines.push(`-- =============================================================================`)

  for (const rel of relationships) {
    const idxName = `idx_${rel.toTable}_${rel.fromField}`
    lines.push(`CREATE INDEX IF NOT EXISTS ${idxName} ON ${rel.toTable} (${rel.fromField});`)
  }

  lines.push('')
  return lines.join('\n')
}

/**
 * Generates SQL DDL directly from a PrdModel.
 */
export function generateSqlFromPrd(model: PrdModel, dialect: SqlDialect = 'postgresql'): string {
  const entities = parseDataModels(model.data_models || '')
  return generateSqlDdl(entities, dialect)
}
